"""本地化协议说明文件：写入 RP/BP 根目录，声明禁止商用付费出售等条款。"""
from __future__ import annotations

from pathlib import Path

from .languages import DEFAULT_CODE, TOOL_NAME_HAN, TOOL_NAME_LATIN, label_of

LICENSE_FILENAME = "本地化协议_LOCALIZATION_LICENSE.txt"
REPO_URL = "https://github.com/ARC-Minecraft/ARC-MCBE-Addon-Auto-Localizer"


